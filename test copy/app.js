// Setup Quill rich text editor
function initQuill() {
  quill = new Quill("#editor", {
    theme: "snow",
    placeholder: "Tell your story... Use headers, bold text, blocks of code, and bullet lists.",
    modules: {
      toolbar: [
        [{ 'header': [1, 2, false] }],
        ['bold', 'italic', 'underline', 'strike'],
        ['blockquote', 'code-block'],
        [{ 'list': 'ordered'}, { 'list': 'bullet' }],
        ['link', 'image'],
        ['clean']
      ]
    }
  });

  // Calculate read time on editor text change
  quill.on("text-change", () => {
    const text = quill.getText();
    const wordCount = text.trim().split(/\s+/).filter(w => w.length > 0).length;
    const autoMinutes = Math.max(1, Math.ceil(wordCount / 200));
    
    readTimeIndicator.textContent = `Auto-calculated: ${autoMinutes} min`;
    
    // Only autofill input if it is empty or user hasn't typed in it
    if (!readTimeInput.value || readTimeInput.dataset.overridden === "false") {
      readTimeInput.value = autoMinutes;
      readTimeInput.dataset.overridden = "false";
    }
  });
}

