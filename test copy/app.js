// Generate SQLAlchemy SQL inserts
function generateSQLScript() {
  let sql = `-- SQLAlchemy Blog Seed Data Script\n`;
  sql += `-- Auto-generated by Antigravity Blog Studio\n`;
  sql += `-- Compatible with SQLAlchemy Post & Tag Models\n\n`;

  // Get active tags from all posts to seed tags table
  const allTags = new Set();
  posts.forEach(post => {
    post.tags.forEach(tag => allTags.add(tag.toUpperCase().replace(/'/g, "''")));
  });

  sql += `-- Seed tags table\n`;
  allTags.forEach(tag => {
    sql += `INSERT INTO tags (name) VALUES ('${tag}') ON CONFLICT(name) DO NOTHING;\n`;
  });
  sql += `\n`;

  sql += `-- Seed posts and post-tag relations\n`;
  posts.forEach(post => {
    const escapedSlug = post.slug.replace(/'/g, "''");
    const escapedTitle = post.title.replace(/'/g, "''");
    const escapedDesc = post.desc.replace(/'/g, "''");
    
    // Quill saves formatted html body content
    const escapedContent = post.content.replace(/'/g, "''");
    const escapedImage = (post.image || "").replace(/'/g, "''");
    const publishedDate = post.date; // YYYY-MM-DD
    const isPinned = post.pinned ? 1 : 0;
    
    sql += `-- Seed Post: "${escapedTitle}"\n`;
    sql += `INSERT INTO posts (slug, title, desc, content, published_date, read_time_minutes, pinned, image, created_at, updated_at)\n`;
    sql += `VALUES (\n`;
    sql += `  '${escapedSlug}',\n`;
    sql += `  '${escapedTitle}',\n`;
    sql += `  '${escapedDesc}',\n`;
    sql += `  '${escapedContent}',\n`;
    sql += `  '${publishedDate}',\n`;
    sql += `  ${post.readTime},\n`;
    sql += `  ${isPinned},\n`;
    sql += `  ${escapedImage ? `'${escapedImage}'` : 'NULL'},\n`;
    sql += `  CURRENT_TIMESTAMP,\n`;
    sql += `  CURRENT_TIMESTAMP\n`;
    sql += `) ON CONFLICT(slug) DO UPDATE SET\n`;
    sql += `  title = excluded.title,\n`;
    sql += `  desc = excluded.desc,\n`;
    sql += `  content = excluded.content,\n`;
    sql += `  published_date = excluded.published_date,\n`;
    sql += `  read_time_minutes = excluded.read_time_minutes,\n`;
    sql += `  pinned = excluded.pinned,\n`;
    sql += `  image = excluded.image,\n`;
    sql += `  updated_at = CURRENT_TIMESTAMP;\n\n`;

    // Map tags
    post.tags.forEach(tag => {
      const escapedTag = tag.toUpperCase().replace(/'/g, "''");
      sql += `-- Map Tag "${escapedTag}" to "${escapedTitle}"\n`;
      sql += `INSERT INTO post_tag (post_id, tag_id)\n`;
      sql += `VALUES (\n`;
      sql += `  (SELECT id FROM posts WHERE slug = '${escapedSlug}'),\n`;
      sql += `  (SELECT id FROM tags WHERE name = '${escapedTag}')\n`;
      sql += `) ON CONFLICT DO NOTHING;\n\n`;
    });
  });

  return sql;
}

// Open SQL Modal
function openSqlModal() {
  if (posts.length === 0) {
    showToast("No posts available to export.", "warning");
    return;
  }
  const sqlContent = generateSQLScript();
  sqlCodeContainer.textContent = sqlContent;
  sqlModal.classList.remove("hidden");
}

// Copy SQL to Clipboard
function copySqlToClipboard() {
  const sqlText = sqlCodeContainer.textContent;
  navigator.clipboard.writeText(sqlText)
    .then(() => showToast("SQL Script copied to clipboard!"))
    .catch(() => showToast("Failed to copy text.", "warning"));
}

// Download SQL Script as File
function downloadSqlFile() {
  const sqlText = sqlCodeContainer.textContent;
  const blob = new Blob([sqlText], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "seed_portfolio_blogs.sql";
  a.click();
  URL.revokeObjectURL(url);
  showToast("SQL file downloaded successfully!");
}

// Export database as JSON file
function exportJSONBackup() {
  if (posts.length === 0) {
    showToast("No posts available to backup.", "warning");
    return;
  }
  const jsonStr = JSON.stringify(posts, null, 2);
  const blob = new Blob([jsonStr], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "blog_studio_backup.json";
  a.click();
  URL.revokeObjectURL(url);
  showToast("Backup JSON exported successfully!");
}

// Import database from JSON file
function importJSONBackup(e) {
  const file = e.target.files[0];
  if (!file) return;

  const reader = new FileReader();
  reader.onload = function(event) {
    try {
      const importedData = JSON.parse(event.target.result);
      if (!Array.isArray(importedData)) {
        throw new Error("Invalid backup file: Root must be a JSON array.");
      }
      
      // Basic validation of import schema
      const isValid = importedData.every(item => 
        item.title && item.slug && item.content && Array.isArray(item.tags)
      );

      if (!isValid) {
        throw new Error("Invalid schema structure. Make sure import contains title, slug, content and tags.");
      }

      if (confirm(`Do you want to overwrite your existing ${posts.length} posts with ${importedData.length} imported posts?`)) {
        posts = importedData;
        saveToLocalStorage();
        currentPostId = null;
        resetEditor();
        renderPostsList();
        showToast("Backup restored successfully!");
      }
    } catch(err) {
      alert(`Import failed: ${err.message}`);
    }
    // Reset file input value so same file can be imported again
    importJsonFile.value = "";
  };
  reader.readAsText(file);
}
