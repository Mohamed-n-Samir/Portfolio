// Generate a URL friendly slug
function generateSlug(text) {
  return text
    .toString()
    .toLowerCase()
    .normalize('NFD') // split accented characters into their base letters and diacritical marks
    .replace(/[\u0300-\u036f]/g, '') // remove diacritical marks
    .replace(/\s+/g, '-') // replace spaces with hyphens
    .replace(/[^\w\-]+/g, '') // remove non-word chars (except hyphens)
    .replace(/\-\-+/g, '-') // replace multiple hyphens with single hyphen
    .replace(/^-+/, '') // trim leading hyphens
    .replace(/-+$/, ''); // trim trailing hyphens
}

// Load data from LocalStorage
function loadData() {
  const localData = localStorage.getItem("antigravity_blogs");
  if (localData) {
    posts = JSON.parse(localData);
  } else {
    // Load default seed data
    posts = [...SEED_POSTS];
    saveToLocalStorage();
  }
}

// Save database to LocalStorage
function saveToLocalStorage() {
  localStorage.setItem("antigravity_blogs", JSON.stringify(posts));
}

// Reset Editor fields
function resetEditor() {
  titleInput.value = "";
  slugInput.value = "";
  slugPreview.textContent = "my-post-slug";
  isSlugAuto = true;
  slugPreview.classList.remove("hidden");
  slugInput.classList.add("hidden");
  slugLockText.textContent = "Auto";
  slugLockIcon.setAttribute("data-lucide", "lock");

  descTextarea.value = "";
  
  // Set date to today
  const today = new Date().toISOString().split("T")[0];
  dateInput.value = today;
  
  readTimeInput.value = "";
  readTimeInput.dataset.overridden = "false";
  readTimeIndicator.textContent = "Auto-calculating...";
  
  pinnedCheckbox.checked = false;
  imageInput.value = "";
  updateImagePreview("");
  
  activeTags = [];
  renderTags();
  
  if (quill) {
    quill.setContents([]);
  }

  btnDelete.classList.add("hidden");
  
  // Remove highlighted selection in sidebar
  const cards = document.querySelectorAll(".post-card");
  cards.forEach(card => card.classList.remove("post-card-active"));
  
  lucide.createIcons();
}

// Load a specific post into the editor
function loadPost(postId) {
  const post = posts.find(p => p.id === postId);
  if (!post) return;

  currentPostId = post.id;
  
  titleInput.value = post.title;
  slugInput.value = post.slug;
  slugPreview.textContent = post.slug;
  
  // Set custom slug state
  isSlugAuto = false;
  slugPreview.classList.add("hidden");
  slugInput.classList.remove("hidden");
  slugLockText.textContent = "Custom";
  slugLockIcon.setAttribute("data-lucide", "unlock");

  descTextarea.value = post.desc || "";
  dateInput.value = post.date;
  readTimeInput.value = post.readTime;
  readTimeInput.dataset.overridden = "true";
  
  pinnedCheckbox.checked = !!post.pinned;
  imageInput.value = post.image || "";
  updateImagePreview(post.image || "");
  
  activeTags = [...(post.tags || [])];
  renderTags();
  
  if (quill) {
    quill.root.innerHTML = post.content || "";
  }

  btnDelete.classList.remove("hidden");
  
  // Highlight card in sidebar
  const cards = document.querySelectorAll(".post-card");
  cards.forEach(card => {
    if (card.dataset.id === postId) {
      card.classList.add("post-card-active");
    } else {
      card.classList.remove("post-card-active");
    }
  });

  lucide.createIcons();
}

// Save post to database
function savePost() {
  const title = titleInput.value.trim();
  const desc = descTextarea.value.trim();
  const date = dateInput.value;
  const content = quill.root.innerHTML.trim();
  const rawText = quill.getText().trim();

  // Basic validations
  if (!title) {
    showToast("Please enter a title.", "warning");
    titleInput.focus();
    return;
  }
  if (!desc) {
    showToast("Please enter a short summary description.", "warning");
    descTextarea.focus();
    return;
  }
  if (rawText.length === 0) {
    showToast("Please write some content in the blog body.", "warning");
    return;
  }

  // Double check slug uniqueness
  const slug = slugInput.value.trim() || generateSlug(title);
  const duplicate = posts.find(p => p.slug === slug && p.id !== currentPostId);
  if (duplicate) {
    showToast(`The slug "${slug}" is already in use by another post!`, "warning");
    slugInput.focus();
    return;
  }

  const readTime = parseInt(readTimeInput.value) || 1;
  const pinned = pinnedCheckbox.checked;
  const image = imageInput.value.trim();

  const nowISO = new Date().toISOString();

  if (currentPostId) {
    // Update existing post
    const index = posts.findIndex(p => p.id === currentPostId);
    if (index !== -1) {
      posts[index] = {
        ...posts[index],
        title,
        slug,
        desc,
        content,
        date,
        readTime,
        pinned,
        image,
        tags: [...activeTags],
        updated_at: nowISO
      };
      showToast("Post updated successfully!");
    }
  } else {
    // Create new post
    const newPost = {
      id: "post-" + Date.now(),
      title,
      slug,
      desc,
      content,
      date,
      readTime,
      pinned,
      image,
      tags: [...activeTags],
      created_at: nowISO,
      updated_at: nowISO
    };
    posts.unshift(newPost); // Add to beginning
    currentPostId = newPost.id;
    btnDelete.classList.remove("hidden");
    showToast("Post created successfully!");
  }

  saveToLocalStorage();
  renderPostsList();
  
  // Make sure current card is highlighted
  const cards = document.querySelectorAll(".post-card");
  cards.forEach(card => {
    if (card.dataset.id === currentPostId) {
      card.classList.add("post-card-active");
    } else {
      card.classList.remove("post-card-active");
    }
  });
}

// Delete post
function deletePost() {
  if (!currentPostId) return;
  
  if (confirm("Are you sure you want to permanently delete this post? This action cannot be undone.")) {
    posts = posts.filter(p => p.id !== currentPostId);
    saveToLocalStorage();
    showToast("Post deleted successfully!", "success");
    currentPostId = null;
    resetEditor();
    renderPostsList();
  }
}

// Render active tags badges
function renderTags() {
  // Remove previous badges, leaving the input
  const badges = tagsWrapper.querySelectorAll(".tag-badge");
  badges.forEach(b => b.remove());

  activeTags.forEach((tag, idx) => {
    const badge = document.createElement("span");
    badge.className = "tag-badge text-[10px] font-mono font-bold py-1 px-2.5 rounded flex items-center gap-1.5";
    badge.innerHTML = `
      ${tag}
      <button class="hover:text-white transition" onclick="removeTag(${idx})">
        <i data-lucide="x" class="w-3 h-3"></i>
      </button>
    `;
    tagsWrapper.insertBefore(badge, tagInput);
  });
  
  lucide.createIcons();
}

// Remove tag helper
window.removeTag = function(index) {
  activeTags.splice(index, 1);
  renderTags();
};

// Update Featured Image preview container
