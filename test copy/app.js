// Render the sidebar list of posts
function renderPostsList() {
  const query = searchInput.value.toLowerCase().trim();
  postsListContainer.innerHTML = "";

  const filteredPosts = posts.filter(p => 
    p.title.toLowerCase().includes(query) || 
    p.desc.toLowerCase().includes(query) ||
    p.tags.some(tag => tag.toLowerCase().includes(query))
  );

  if (filteredPosts.length === 0) {
    postsListContainer.innerHTML = `
      <div class="text-center py-8 text-muted-foreground text-xs border border-dashed border-border rounded-xl">
        No matches found.
      </div>
    `;
    return;
  }

  filteredPosts.forEach(post => {
    const card = document.createElement("div");
    card.className = `post-card panel p-4 cursor-pointer flex flex-col gap-2 hover:bg-panel-2/50 transition duration-300 relative ${post.id === currentPostId ? 'post-card-active' : ''}`;
    card.dataset.id = post.id;
    
    // Build tags badges
    const tagsBadges = post.tags.slice(0, 3).map(tag => 
      `<span class="text-[9px] font-bold px-1.5 py-0.5 rounded bg-muted/60 text-muted-foreground">${tag}</span>`
    ).join(" ");

    card.innerHTML = `
      <div class="flex justify-between items-start gap-2">
        <h3 class="text-xs font-bold text-foreground line-clamp-2 font-display hover:text-accent transition">${post.title}</h3>
        ${post.pinned ? `<i data-lucide="pin" class="w-3.5 h-3.5 text-accent flex-shrink-0" title="Pinned to Featured"></i>` : ''}
      </div>
      <p class="text-[10px] text-muted-foreground line-clamp-2">${post.desc || ''}</p>
      <div class="flex items-center justify-between mt-1 text-[9px] font-mono text-muted-foreground">
        <span>${formatDateDisplay(post.date)}</span>
        <span>${post.readTime} min read</span>
      </div>
      <div class="flex flex-wrap gap-1 mt-1">
        ${tagsBadges}
      </div>
    `;

    card.addEventListener("click", () => loadPost(post.id));
    postsListContainer.appendChild(card);
  });

  lucide.createIcons();
}

// Convert YYYY-MM-DD to "MMM DD, YYYY" (e.g. Feb 10, 2026) for display
function formatDateDisplay(dateStr) {
  if (!dateStr) return "";
  const parts = dateStr.split("-");
  if (parts.length !== 3) return dateStr;
  
  const dateObj = new Date(parts[0], parts[1] - 1, parts[2]);
  return dateObj.toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric'
  });
}

// Toast Notifications
